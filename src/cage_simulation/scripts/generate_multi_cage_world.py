#!/usr/bin/env python3
"""Generate independently deformed cage models, one world, and aggregate GT."""
import argparse
import copy
import hashlib
import json
import math
import os
import sys

import yaml


HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from generate_fish_farm import generate  # noqa: E402


def _write_model_config(model_dir, model_name):
    text = """<?xml version="1.0"?>
<model>
  <name>{name}</name>
  <version>1.0</version>
  <sdf version="1.6">model.sdf</sdf>
  <author><name>cage_uav</name></author>
  <description>Deterministic independently deformed fish-farm lattice.</description>
</model>
""".format(name=model_name)
    with open(os.path.join(model_dir, 'model.config'), 'w', encoding='utf-8') as stream:
        stream.write(text)


def _transform_enu(point, pose):
    """Apply a Gazebo model pose to an ENU point.

    Existing project convention is Gazebo world x=north and y=-east.  A world
    yaw is therefore the same positive planar yaw when expressed in ENU.
    """
    east, north, up = map(float, point)
    world_x, world_y, world_z, _roll, _pitch, yaw = map(float, pose)
    cosine, sine = math.cos(yaw), math.sin(yaw)
    rotated_east = cosine * east - sine * north
    rotated_north = sine * east + cosine * north
    return [rotated_east - world_y, rotated_north + world_x, up + world_z]


def _transform_manifest(manifest, pose, name, targetable):
    result = copy.deepcopy(manifest)
    result['name'] = name
    result['targetable'] = bool(targetable)
    result['model_pose_world'] = list(map(float, pose))
    result['effective_yaw_deg'] = float(result.get('yaw_deg', 0.0)) + math.degrees(float(pose[5]))
    result['anchor_enu'] = _transform_enu(result['anchor_enu'], pose)
    for vertex in result['vertices']:
        vertex['enu'] = _transform_enu(vertex['enu'], pose)
    for cell in result['cells']:
        cell['center_enu'] = _transform_enu(cell['center_enu'], pose)
        cell['polygon_enu'] = [_transform_enu(point, pose) for point in cell['polygon_enu']]
    result.pop('geometry_sha256', None)
    canonical = json.dumps(result, sort_keys=True, separators=(',', ':'))
    result['geometry_sha256'] = hashlib.sha256(canonical.encode('utf-8')).hexdigest()
    return result


def _world_text(cages):
    includes = []
    for cage in cages:
        pose = ' '.join('{:.9g}'.format(float(value)) for value in cage['pose'])
        includes.append(
            '    <include><name>{name}</name><uri>model://{model}</uri>'
            '<pose>{pose}</pose></include>'.format(
                name=cage['name'], model=cage['model_name'], pose=pose))
    return """<?xml version="1.0"?>
<!-- Generated by generate_multi_cage_world.py. Do not hand-edit. -->
<sdf version="1.6">
  <world name="default">
    <physics type="ode">
      <real_time_update_rate>1000</real_time_update_rate>
      <max_step_size>0.001</max_step_size>
    </physics>
    <gravity>0 0 -9.8</gravity>
    <scene>
      <ambient>0.48 0.54 0.53 1</ambient>
      <background>0.44 0.53 0.54 1</background>
      <shadows>true</shadows>
      <sky><time>12</time><sunrise>6</sunrise><sunset>19</sunset>
        <clouds><speed>0.15</speed><direction>0.4</direction><humidity>0.20</humidity>
          <mean_size>0.45</mean_size><ambient>0.85 0.88 0.92 1</ambient></clouds>
      </sky>
    </scene>
    <gui fullscreen="false">
      <camera name="mission_overview"><pose>38 -116 112 0.58 0.0 -1.57</pose></camera>
    </gui>
    <include><uri>model://sun</uri></include>
    <include><uri>model://water_surface</uri></include>
    <include><name>iris_demo</name><uri>model://iris_with_ardupilot</uri></include>
{includes}
  </world>
</sdf>
""".format(includes='\n'.join(includes))


def generate_multi(fish_farm_config, layout_config, models_dir, world_output,
                   aggregate_gt_output, deformation_preset=None,
                   deformation_seed=None):
    with open(layout_config, encoding='utf-8') as stream:
        layout = (yaml.safe_load(stream) or {}).get('multi_cage_layout', {})
    cages = list(layout.get('cages', []))
    if not cages:
        raise ValueError('multi_cage_layout.cages must not be empty')
    ids = [int(item['id']) for item in cages]
    if len(ids) != len(set(ids)):
        raise ValueError('cage ids must be unique')

    generated = []
    transformed = []
    for item in cages:
        cage_id = int(item['id'])
        name = str(item.get('name', 'CAGE_{}'.format(cage_id)))
        pose = item.get('pose', [0.0] * 6)
        if len(pose) != 6:
            raise ValueError('{} pose must contain six values'.format(name))
        seed = (int(deformation_seed) + cage_id * 1009
                if deformation_seed is not None
                else int(item.get('deformation_seed', 42 + cage_id * 1009)))
        model_name = 'fish_farm_cage_{}'.format(cage_id)
        model_dir = os.path.join(models_dir, model_name)
        sdf_path = os.path.join(model_dir, 'model.sdf')
        gt_path = os.path.join(os.path.dirname(aggregate_gt_output), '{}_gt.json'.format(model_name))
        os.makedirs(model_dir, exist_ok=True)
        result = generate(fish_farm_config, sdf_path, gt_path, model_name,
                          cage_id=cage_id, geometry_seed=seed,
                          deformation_preset=deformation_preset)
        _write_model_config(model_dir, model_name)
        with open(gt_path, encoding='utf-8') as stream:
            manifest = json.load(stream)
        transformed.append(_transform_manifest(
            manifest, pose, name, item.get('targetable', False)))
        generated.append({
            'id': cage_id,
            'name': name,
            'model_name': model_name,
            'targetable': bool(item.get('targetable', False)),
            'pose': list(map(float, pose)),
            'seed': seed,
            'model': sdf_path,
            'ground_truth': gt_path,
            'geometry_sha256': result['geometry_sha256'],
        })

    os.makedirs(os.path.dirname(world_output), exist_ok=True)
    with open(world_output, 'w', encoding='utf-8') as stream:
        stream.write(_world_text(generated))
    aggregate = {
        'schema_version': 1,
        'frame_id': 'map',
        'active_cage_id': int(layout.get('active_cage_id', 0)),
        'cages': transformed,
    }
    canonical = json.dumps(aggregate, sort_keys=True, separators=(',', ':'))
    aggregate['aggregate_sha256'] = hashlib.sha256(canonical.encode('utf-8')).hexdigest()
    os.makedirs(os.path.dirname(aggregate_gt_output), exist_ok=True)
    with open(aggregate_gt_output, 'w', encoding='utf-8') as stream:
        json.dump(aggregate, stream, indent=2, sort_keys=True)
        stream.write('\n')
    return {
        'world': world_output,
        'ground_truth': aggregate_gt_output,
        'aggregate_sha256': aggregate['aggregate_sha256'],
        'cages': generated,
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--fish-farm-config', required=True)
    parser.add_argument('--layout-config', required=True)
    parser.add_argument('--models-dir', required=True)
    parser.add_argument('--world-output', required=True)
    parser.add_argument('--ground-truth-output', required=True)
    parser.add_argument('--deformation-preset', choices=('mild', 'medium', 'strong'))
    parser.add_argument('--deformation-seed', type=int)
    args = parser.parse_args()
    result = generate_multi(args.fish_farm_config, args.layout_config,
                            args.models_dir, args.world_output,
                            args.ground_truth_output,
                            args.deformation_preset, args.deformation_seed)
    print('generated {} independent cages; world={}; gt={}; sha256={}'.format(
        len(result['cages']), result['world'], result['ground_truth'],
        result['aggregate_sha256']))


if __name__ == '__main__':
    main()
